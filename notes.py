# notebooks/employee_analysis.ipynb
# - Load the raw CSV.
# - Check missing values.
# - Remove duplicates.
# - Fix data types.
# - Standardise text.
# - Detect outliers.
# - Create before/after summary.
# - Save clean_data.csv in reports.

# Step 3 – Exploratory Data Analysis

# In the same notebook:
# - Calculate mean, median, min, max and standard deviation.
# - Perform department-wise and city-wise analysis.
# - Find top three correlations.
# - Answer five business questions.
# - Merge department budget data.

